import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const appDirectory = dirname(dirname(fileURLToPath(import.meta.url)));
const publicDirectory = join(appDirectory, 'public');
const indexHtml = await readFile(join(publicDirectory, 'index.html'), 'utf8');

const pages = [
  {
    path: 'privacy.html',
    modalId: 'privacy-modal',
    title: 'Privacy Policy',
    description: 'Privacy Policy for Card AI: TCG Card Scanner.',
  },
  {
    path: 'terms.html',
    modalId: 'terms-modal',
    title: 'Terms of Use',
    description: 'Terms of Use for Card AI: TCG Card Scanner.',
  },
];

for (const page of pages) {
  const content = extractLegalContent(indexHtml, page.modalId);
  await writeFile(
    join(publicDirectory, page.path),
    renderLegalPage(page, content),
    'utf8',
  );
}

function extractLegalContent(html, modalId) {
  const modalMarker = `<div class="legal-modal" id="${modalId}"`;
  const modalStart = html.indexOf(modalMarker);
  if (modalStart === -1) {
    throw new Error(`Missing legal modal: ${modalId}`);
  }

  const articleMarker = '<article class="modal-legal-content">';
  const articleStart = html.indexOf(articleMarker, modalStart);
  const articleEnd = html.indexOf('</article>', articleStart);
  if (articleStart === -1 || articleEnd === -1) {
    throw new Error(`Missing legal content for modal: ${modalId}`);
  }

  return html
    .slice(articleStart + articleMarker.length, articleEnd)
    .trim();
}

