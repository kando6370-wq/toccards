function renderShell({
  url,
  title,
  description,
  jsonLd,
  body,
  indexable = true,
  ogType = 'website',
  image = '/assets/hero-phones.png',
}) {
  const blocks = jsonLd
    .map((entry) => `  <script type="application/ld+json">\n${JSON.stringify(entry, null, 2)}\n  </script>`)
    .join('\n');
  return `<!doctype html>
<!-- Generated by scripts/generate-content.mjs. Edit ./content instead. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="${escapeHtml(description)}">
${indexable ? `  <link rel="canonical" href="${ORIGIN}${url}">` : '  <meta name="robots" content="noindex,follow">'}
  <meta property="og:type" content="${escapeHtml(ogType)}">
  <meta property="og:site_name" content="Card AI">
  <meta property="og:title" content="${escapeHtml(title)}">
  <meta property="og:description" content="${escapeHtml(description)}">
${indexable ? `  <meta property="og:url" content="${ORIGIN}${url}">` : ''}
  <meta property="og:image" content="${ORIGIN}${image}">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${escapeHtml(title)}">
  <meta name="twitter:description" content="${escapeHtml(description)}">
  <meta name="twitter:image" content="${ORIGIN}${image}">
  <link rel="icon" type="image/png" href="/assets/card-ai-logo.png">
  <link rel="apple-touch-icon" href="/assets/card-ai-logo.png">
${blocks}
  <title>${escapeHtml(title)}</title>
  <link rel="stylesheet" href="/site.css">
</head>
<body>
  <div class="marketing-site">
${HEADER}
    <main class="content-main">
${body}
    </main>
${FOOTER}
  </div>
</body>
</html>
`;
}

function renderFaq(faq, heading = 'Questions.') {
  if (!faq?.length) return '';
  const items = faq
    .map(
      ({ q, a }) => `            <details class="faq-item">
              <summary>${escapeHtml(q)}</summary>
              <p>${escapeHtml(a)}</p>
            </details>`,
    )
    .join('\n');
  return `
      <section class="faq-section">
        <div class="faq-layout site-container">
          <h2>${escapeHtml(heading)}</h2>
          <div class="faq-list">
${items}
          </div>
        </div>
      </section>`;
}

function renderProductProof(page) {
  const proof = page.proof;
  const asset = proof && PROOF_ASSETS[proof.kind];
  if (!proof || !asset) throw new Error(`Missing product proof for ${page.slug}`);
  return `      <figure class="product-proof site-container">
        <div class="product-proof-media">
          <img src="${asset.src}" alt="${escapeHtml(`${page.linkLabel}: ${asset.alt}`)}" loading="lazy">
        </div>
        <figcaption>
          <h2>${escapeHtml(proof.title)}</h2>
          <div class="product-proof-copy">
            ${renderMarkdown(proof.body)}
          </div>
          <p class="product-proof-note">Illustrative Card AI screen composite. Values shown are examples; market prices, history, and sold-listing availability depend on the selected card.</p>
        </figcaption>
      </figure>`;
}

function renderLanding(page, all) {
  const ctaLabel = `${page.linkLabel.charAt(0).toLowerCase()}${page.linkLabel.slice(1)}`;
  const sections = page.sections
    .map(
      (section) => `          <section class="content-block">
            <h2>${escapeHtml(section.h2)}</h2>
            ${renderMarkdown(section.body)}
          </section>`,
    )
    .join('\n');

  const related = (page.related ?? [])
    .map((slug) => all.find((candidate) => candidate.slug === slug))
    .filter(Boolean)
    .map((target) => `<li><a href="/${target.slug}">${escapeHtml(target.linkLabel ?? target.h1)}</a></li>`)
    .join('');

  const body = `      <section class="content-hero">
        <div class="site-container">
          <p class="content-eyebrow">${escapeHtml(page.eyebrow)}</p>
          <h1>${escapeHtml(page.h1)}</h1>
          <p class="content-lede">${escapeHtml(page.lede)}</p>
${STORE_ROW}
        </div>
      </section>

${renderProductProof(page)}

      <div class="content-body site-container">
${sections}
${related ? `          <section class="content-block">\n            <h2>Related</h2>\n            <ul class="content-links">${related}</ul>\n          </section>` : ''}
        </div>
${renderFaq(page.faq, `${page.linkLabel ?? page.h1} questions.`)}

      <section class="content-cta">
        <div class="site-container">
          <h2>Try the ${escapeHtml(ctaLabel)} in Card AI.</h2>
          <p>${escapeHtml(page.cta)}</p>
${STORE_ROW}
        </div>
      </section>`;

  const jsonLd = [
    {
      '@context': 'https://schema.org',
      '@type': 'WebPage',
      name: page.title,
      url: `${ORIGIN}/${page.slug}`,
      description: page.description,
      image: `${ORIGIN}${PROOF_ASSETS[page.proof.kind].src}`,
      isPartOf: { '@type': 'WebSite', name: 'Card AI', url: `${ORIGIN}/` },
    },
  ];
  if (page.faq?.length) {
    jsonLd.push({
      '@context': 'https://schema.org',
      '@type': 'FAQPage',
      mainEntity: page.faq.map(({ q, a }) => ({
        '@type': 'Question',
        name: q,
        acceptedAnswer: { '@type': 'Answer', text: a },
      })),
    });
  }
  return renderShell({ url: `/${page.slug}`, title: page.title, description: page.description, jsonLd, body });
}

function renderPost(post) {
  const figure = post.meta.image
    ? `          <figure class="content-figure">
            <img src="${escapeHtml(post.meta.image)}" alt="${escapeHtml(post.meta.imageAlt)}">
            <figcaption>${escapeHtml(post.meta.imageCaption)}</figcaption>
          </figure>`
    : '';
  const body = `      <article class="content-article">
        <div class="site-container">
          <p class="content-eyebrow"><a href="/blog/">Blog</a></p>
          <h1>${escapeHtml(post.meta.h1)}</h1>
          <p class="content-meta"><time datetime="${post.meta.date}">${post.meta.date}</time></p>
${figure}
          <div class="content-prose">
          ${renderMarkdown(post.body)}
          </div>
        </div>
      </article>`;

  const jsonLd = [
    {
      '@context': 'https://schema.org',
      '@type': 'Article',
      headline: post.meta.h1,
      description: post.meta.description,
      image: `${ORIGIN}${post.meta.image}`,
      datePublished: post.meta.date,
      dateModified: post.meta.date,
      mainEntityOfPage: `${ORIGIN}/blog/${post.slug}`,
      author: { '@type': 'Organization', name: 'Card AI', url: `${ORIGIN}/` },
      publisher: {
        '@type': 'Organization',
        name: 'Card AI',
        logo: { '@type': 'ImageObject', url: `${ORIGIN}/assets/card-ai-logo.png` },
      },
    },
    {
      '@context': 'https://schema.org',
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Home', item: `${ORIGIN}/` },
        { '@type': 'ListItem', position: 2, name: 'Blog', item: `${ORIGIN}/blog/` },
        { '@type': 'ListItem', position: 3, name: post.meta.h1 },
      ],
    },
  ];
  return renderShell({
    url: `/blog/${post.slug}`,
    title: post.meta.title,
    description: post.meta.description,
    jsonLd,
    body,
    ogType: 'article',
    image: post.meta.image,
  });
}

