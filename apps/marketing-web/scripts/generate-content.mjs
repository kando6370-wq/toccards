function render404(landing) {
  const links = landing
    .slice(0, 6)
    .map((page) => `<li><a href="/${page.slug}">${escapeHtml(page.linkLabel ?? page.h1)}</a></li>`)
    .join('');
  const body = `      <section class="content-hero">
        <div class="site-container">
          <p class="content-eyebrow">404</p>
          <h1>That page does not exist.</h1>
          <p class="content-lede">The link may be out of date. Here is where to go instead.</p>
          <ul class="content-links" style="margin-top:32px">
            <li><a href="/">Card AI home</a></li>
            <li><a href="/blog/">Blog</a></li>
${links ? `            ${links}` : ''}
          </ul>
        </div>
      </section>`;
  return renderShell({
    url: '/404',
    title: 'Page not found | Card AI',
    description: 'The page you were looking for does not exist.',
    jsonLd: [],
    body,
    indexable: false,
  });
}

const GROUPS = [
  { title: 'Trading card games', match: (p) => p.group === 'tcg' },
  { title: 'Sports cards', match: (p) => p.group === 'sports' },
  { title: 'By feature', match: (p) => p.group === 'feature' },
];

function renderBrowseBlock(landing, posts) {
  const columns = GROUPS.map((group) => {
    const items = landing
      .filter(group.match)
      .map((page) => `<li><a href="/${page.slug}">${escapeHtml(page.linkLabel ?? page.h1)}</a></li>`)
      .join('');
    return items ? `            <div class="browse-col">\n              <h3>${group.title}</h3>\n              <ul class="content-links">${items}</ul>\n            </div>` : '';
  }).filter(Boolean);

  const guides = posts
    .map((post) => `<li><a href="/blog/${post.slug}">${escapeHtml(post.meta.h1)}</a></li>`)
    .join('');
  columns.push(`            <div class="browse-col">\n              <h3>Guides</h3>\n              <ul class="content-links">${guides}<li><a href="/blog/">All guides</a></li></ul>\n            </div>`);

  return `      <section class="browse-section" id="browse">
        <div class="site-container">
          <h2>Browse by game and feature.</h2>
          <div class="browse-grid">
${columns.join('\n')}
          </div>
        </div>
      </section>`;
}

function renderSitemap(urls) {
  const entries = urls
    .map(
      ({ loc, priority }) => `  <url>
    <loc>${ORIGIN}${loc}</loc>
    <priority>${priority}</priority>
  </url>`,
    )
    .join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by scripts/generate-content.mjs. -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries}\n</urlset>\n`;
}

// ---- build ----
const landingFiles = (await readdir(join(contentDirectory, 'landing'))).filter((f) => f.endsWith('.mjs')).sort();
const landing = [];
for (const file of landingFiles) {
  const module = await import(new URL(`../content/landing/${file}`, import.meta.url));
  landing.push(module.default);
}

const blogFiles = (await readdir(join(contentDirectory, 'blog'))).filter((f) => f.endsWith('.md')).sort();
const posts = [];
for (const file of blogFiles) {
  const raw = await readFile(join(contentDirectory, 'blog', file), 'utf8');
  const { meta, body } = parseFrontMatter(raw);
  posts.push({ slug: file.replace(/\.md$/, ''), meta, body });
}
posts.sort((a, b) => b.meta.date.localeCompare(a.meta.date));

for (const page of landing) {
  await writeFile(join(publicDirectory, `${page.slug}.html`), renderLanding(page, landing), 'utf8');
}

await mkdir(join(publicDirectory, 'blog'), { recursive: true });
for (const post of posts) {
  await writeFile(join(publicDirectory, 'blog', `${post.slug}.html`), renderPost(post), 'utf8');
}
await writeFile(join(publicDirectory, 'blog', 'index.html'), renderBlogIndex(posts), 'utf8');

await writeFile(join(publicDirectory, '404.html'), render404(landing), 'utf8');

await writeFile(
  join(publicDirectory, 'sitemap.xml'),
  renderSitemap([
    { loc: '/', priority: '1.0' },
    ...landing.map((page) => ({ loc: `/${page.slug}`, priority: '0.8' })),
    { loc: '/blog/', priority: '0.6' },
    ...posts.map((post) => ({ loc: `/blog/${post.slug}`, priority: '0.5' })),
    { loc: '/privacy', priority: '0.3' },
    { loc: '/terms', priority: '0.3' },
  ]),
  'utf8',
);

console.log(`generated ${landing.length} landing pages, ${posts.length} blog posts, sitemap`);

// index.html 的链接块与 llms.txt 的页面清单由标记区间维护
const indexPath = join(publicDirectory, 'index.html');
let indexHtml = await readFile(indexPath, 'utf8');
indexHtml = indexHtml.replace(
  /<!-- BEGIN generated-links -->[\s\S]*?<!-- END generated-links -->/,
  `<!-- BEGIN generated-links -->\n${renderBrowseBlock(landing, posts)}\n      <!-- END generated-links -->`,
);
await writeFile(indexPath, indexHtml, 'utf8');

const llmsPath = join(publicDirectory, 'llms.txt');
let llms = await readFile(llmsPath, 'utf8');
const llmsList = [
  ...landing.map((page) => `- [${page.linkLabel ?? page.h1}](${ORIGIN}/${page.slug}): ${page.description}`),
  `- [Blog](${ORIGIN}/blog/): Guides on card values, grading, and collection tracking.`,
  ...posts.map((post) => `- [${post.meta.h1}](${ORIGIN}/blog/${post.slug}): ${post.meta.description}`),
].join('\n');
llms = llms.replace(
  /(## Pages\n\n)[\s\S]*?(\n\n## )/,
  `$1${llmsList}$2`,
);
await writeFile(llmsPath, llms, 'utf8');

console.log('index links + llms.txt updated');
